-- Doorgunner online backend, migration 1: extensions, tables, RLS.
-- Run the migrations in order (001 .. 005) in the Supabase SQL editor. All of them are safe to re-run.

create schema if not exists extensions;
create extension if not exists citext   with schema extensions;
create extension if not exists unaccent with schema extensions;

-- One row per anonymous Supabase user (id = auth.uid()). Written only through the RPCs in 003.
create table if not exists public.players (
  id         uuid primary key,
  name       extensions.citext not null unique,
  avatar     smallint not null check (avatar between 0 and 11),  -- 12 portraits (P4)
  created_at timestamptz not null default now(),
  hidden     boolean not null default false                       -- moderation: set true in the dashboard
);

-- One row per run. Written only by upsert_run (004). points is computed on the server.
create table if not exists public.runs (
  id           uuid primary key,                                   -- generated by the client
  player_id    uuid not null references public.players(id) on delete cascade,
  started_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  ended        boolean not null default false,
  victory      boolean not null default false,
  day          int not null check (day >= 1),
  rescued      int not null default 0 check (rescued >= 0),
  kills        int not null default 0 check (kills >= 0),
  modifiers    text[] not null default '{}',
  points       int not null default 0,
  game_version text
);
create index if not exists runs_player_idx on public.runs (player_id, started_at desc);

-- Name filter lists. Words are normalized: lowercase a-z only (see name_normalize in 002).
-- The INSERTs are generated from data/banned_words.txt / data/allowed_words.txt by tools/gen_wordlist_sql.py (P3).
create table if not exists public.banned_words (
  word text primary key check (word ~ '^[a-z]{3,}$'),
  lang text
);
create table if not exists public.allowed_words (
  word text primary key check (word ~ '^[a-z]{3,}$')
);

-- Score factors of the run modifiers. Rows are added by P15; unknown ids count as 1.0.
create table if not exists public.modifiers (
  id     text primary key,
  factor numeric not null check (factor > 0)
);

-- RLS: nobody writes directly. Table owner (postgres) and the security definer RPCs bypass RLS.
alter table public.players       enable row level security;
alter table public.runs          enable row level security;
alter table public.banned_words  enable row level security;
alter table public.allowed_words enable row level security;
alter table public.modifiers     enable row level security;

revoke all on public.players, public.runs, public.banned_words, public.allowed_words, public.modifiers
  from anon, authenticated;

-- Everyone may read players (not hidden ones; a hidden player still sees themself).
grant select on public.players to anon, authenticated;
drop policy if exists players_read on public.players;
create policy players_read on public.players for select to anon, authenticated
  using (not hidden or id = auth.uid());

-- A player may read their own runs (for resuming / "my rank"); the leaderboards go through the views in 005.
grant select on public.runs to authenticated;
drop policy if exists runs_read_own on public.runs;
create policy runs_read_own on public.runs for select to authenticated
  using (player_id = auth.uid());

-- Modifier factors are public (the client shows them on the NEW RUN screen).
grant select on public.modifiers to anon, authenticated;
drop policy if exists modifiers_read on public.modifiers;
create policy modifiers_read on public.modifiers for select to anon, authenticated using (true);

