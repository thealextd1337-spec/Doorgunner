#!/usr/bin/env python3
"""Writes server/supabase/zz_wordlists.sql (INSERTs for banned_words / allowed_words) from data/*.txt.
Normalization must match scripts/name_filter.gd and the server's name_ok(): lowercase, unaccent,
leetspeak 0->o 1->i 3->e 4->a 5->s 7->t @->a $->s, keep a-z only. Run from anywhere: python tools/gen_wordlist_sql.py"""
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIN_LEN = 3
LEET = str.maketrans("013457@$", "oieastas")


def normalize(text: str) -> str:
    text = text.lower().replace("ß", "ss")
    text = "".join(c for c in unicodedata.normalize("NFKD", text) if not unicodedata.combining(c))
    return re.sub(r"[^a-z]", "", text.translate(LEET))


def read_words(path: Path):
    """Yields (lang, normalized word); lang comes from '[lang]' headers, '' before the first one."""
    lang = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("["):
            lang = line.strip("[]")
            continue
        w = normalize(line)
        if len(w) >= MIN_LEN:
            yield lang, w


def main() -> None:
    banned = {}
    for lang, w in read_words(ROOT / "data" / "banned_words.txt"):
        banned.setdefault(w, lang)
    allowed = sorted({w for _, w in read_words(ROOT / "data" / "allowed_words.txt")})
    out = ["-- Generated by tools/gen_wordlist_sql.py from data/*.txt. Do not edit; run after banned_words / allowed_words are created.",
           "-- Word lists derived in part from LDNOOBW (CC BY 4.0), see data/ATTRIBUTION.md.",
           "truncate banned_words;", "truncate allowed_words;"]
    out.append("insert into banned_words (word, lang) values")
    out.append(",\n".join(f"  ('{w}', '{l}')" for w, l in sorted(banned.items())) + ";")
    out.append("insert into allowed_words (word) values")
    out.append(",\n".join(f"  ('{w}')" for w in allowed) + ";")
    dest = ROOT / "server" / "supabase" / "zz_wordlists.sql"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {dest}: {len(banned)} banned, {len(allowed)} allowed")


if __name__ == "__main__":
    main()
